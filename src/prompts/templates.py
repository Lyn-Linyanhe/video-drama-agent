def render_prompt(template: str, **kwargs) -> str:
    """渲染提示词模板，替换占位变量。

    Args:
        template: 模板字符串（使用 {var} 或 {{var}} 格式）
        **kwargs: 要替换的变量

    Returns:
        渲染后的提示词字符串
    """
    # 将双花括号 {{}} 还原为单花括号（用于 JSON 示例中的花括号）
    return template.format(**kwargs)
